'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
(async () => {
  const dom = new JSDOM('<body></body>', { url: 'https://panthorium.test', runScripts: 'outside-only' });
  const w = dom.window, revoked = [], requests = [];
  w.OS = { state: { user: { sub: 'alice' } }, config: { backendUrl: 'https://panthorium.test' } };
  w.createWindow = (id, title, markup) => { const root = w.document.createElement('div'); root.className = 'window'; root.innerHTML = markup; w.document.body.append(root); };
  w.closeWindow = () => w.document.querySelector('.window')?.remove();
  w.URL.createObjectURL = () => 'blob:private-preview'; w.URL.revokeObjectURL = url => revoked.push(url);
  let response;
  w.authorizedFetch = async (url, init) => { requests.push({url,init}); return response; };
  const reply = (type, body, format = 'original') => ({ ok: true, headers: { get: key => key === 'content-type' ? type : format }, text: async () => body, blob: async () => new w.Blob([body], { type }) });
  w.eval(fs.readFileSync(require.resolve('../file-preview-ui.js'), 'utf8'));
  const viewer = w.PanthoriumFilePreview;
  response = reply('text/html', '<h1>รายงาน</h1><table><tr><td>100</td></tr></table><script>alert(1)</script><img src="https://bad.test/x"><iframe src="https://bad.test"></iframe><a href="javascript:alert(1)">link</a>');
  assert.equal(await viewer.open({id:'html',name:'<img onerror=alert(1)>'}), true);
  let frame = w.document.querySelector('iframe');
  assert.equal(frame.getAttribute('sandbox'), '');
  assert.match(frame.srcdoc, /<h1>รายงาน<\/h1>/); assert.match(frame.srcdoc, /<td>100<\/td>/);
  assert.doesNotMatch(frame.srcdoc, /<script|bad.test|javascript:|onerror=/);
  assert.equal(w.document.querySelector('[data-file-preview-name]').textContent, '<img onerror=alert(1)>');
  assert.ok(requests[0].url.endsWith('/api/files/html/preview'));
  response = reply('video/mp4', 'video bytes');
  await viewer.open({id:'video',name:'video.mp4'});
  const video = w.document.querySelector('video');
  assert.ok(video.controls); assert.equal(video.autoplay, false); assert.equal(video.src, 'blob:private-preview');
  // Token refresh for the same owner preserves the viewer.
  w.dispatchEvent(new w.Event('panthorium:auth-changed')); assert.ok(video.isConnected);
  w.OS.state.user = {sub:'bob'}; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  assert.equal(w.document.querySelector('video'), null); assert.deepEqual(revoked, ['blob:private-preview']);
  response = reply('text/plain', 'สินค้า\t100', 'office-text');
  await viewer.open({id:'sheet',name:'sheet.xlsx'});
  assert.match(w.document.querySelector('pre').textContent, /สินค้า\t100/);
  assert.match(w.document.querySelector('[data-file-preview-note]').textContent, /บางส่วน/);
  let resolveLate;
  w.authorizedFetch = () => new Promise(resolve => { resolveLate = resolve; });
  const pending = viewer.open({id:'late',name:'late.txt'});
  w.OS.state.user = {sub:'charlie'}; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  resolveLate(reply('text/plain','private late body'));
  assert.equal(await pending, false); assert.doesNotMatch(w.document.body.textContent, /private late body/);
  response = {ok:false,status:415,json:async()=>({error:'file_preview_unsupported'})};
  w.authorizedFetch = async () => response;
  assert.equal(await viewer.open({id:'zip',name:'archive.zip'}), false);
  assert.match(w.document.querySelector('[data-file-preview-note]').textContent, /ชนิดนี้/);
  viewer.close();
  w.OS.state.user = {sub:'guest:123'}; assert.equal(await viewer.open({id:'private'}), false);
  dom.window.close();
  console.log('PASS file preview: safe HTML/text, private media, read-only Office, typed errors, account switches and late-response cleanup');
})().catch(error => { console.error(error); process.exitCode = 1; });
