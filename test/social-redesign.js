"use strict";
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { SocialRepository } = require("../services/socialRepository");
const { SocialService } = require("../services/socialService");
async function suite(repo) {
  await repo.init();
  const [a,b,c,d] = Array.from({length:4}, () => ({sub:randomUUID(),roles:["user"],permissions:["chat"]}));
  const image = {id:randomUUID(), name:"photo.png",size:12,contentType:"image/png"}, video = {id:randomUUID(),name:"clip.mp4",size:30,contentType:"video/mp4"};
  const files = {findObject:async (uid,id) => { const file = [image,video].find(f => f.id===id); if(uid!==a.sub||!file) throw Error("file_not_found"); return file; }, preview:async()=>({body:Buffer.from("image")})};
  const s = new SocialService({repository:repo,files});
  const write = (user,action,input={}) => s.write({user,action,input,requestId:randomUUID()});
  for (const [i,user] of [a,b,c,d].entries()) await write(user,"profile",{name:["Alice","Betty","Carl","Doris"][i],bio:"Private bio "+i,discoverable:true,...(i===0?{fileIds:[image.id]}:{})});
  assert.equal((await s.people({user:b,query:"Alice"})).items[0].bio, undefined);
  assert.deepEqual(Object.keys((await s.people({user:b,query:"Alice"})).items[0]).sort(),["friendship","id","name"]);
  await assert.rejects(()=>s.read({user:b,recordId:"profile:"+a.sub}),/social_not_found/);
  await assert.rejects(()=>s.media({user:b,recordId:"profile:"+a.sub,fileId:image.id}),/social_not_found/);
  assert.equal((await s.profile(a)).bio,"Private bio 0");
  await assert.rejects(()=>write(a,"profile",{name:"Alice",fileIds:[video.id]}),/social_image_required/);
  const post=(await write(a,"publish",{module:"watch",text:"Image and text",fileIds:[image.id]})).record;
  await write(a,"publish",{module:"watch",text:"Text only"});
  await assert.rejects(()=>write(a,"publish",{module:"watch",fileIds:[video.id]}),/social_watch_images_only/);
  await assert.rejects(()=>write(a,"publish",{module:"short",text:"Missing video"}),/social_video_required/);
  const clip=(await write(a,"publish",{module:"short",fileIds:[video.id]})).record;
  const legacy={...clip,id:"legacy:"+randomUUID(),kind:"watch"}; await repo.put(legacy);
  const comment=(await write(b,"comment",{recordId:legacy.id,text:"Original comment"})).record;
  const shorts=(await s.read({user:b,module:"short"})).items;
  assert(shorts.some(r=>r.id===clip.id)&&shorts.some(r=>r.id===legacy.id));
  assert(!(await s.read({user:b,module:"watch"})).items.some(r=>r.files.some(f=>f.contentType.startsWith("video/"))));
  const old=(await s.read({user:b,recordId:legacy.id})); assert.equal(old.record.module,"short");assert.equal(old.items[0].id,comment.id);
  await write(a,"edit",{recordId:legacy.id,audience:"private"});
  assert(!(await s.read({user:b,module:"short"})).items.some(r=>r.id===legacy.id));
  await assert.rejects(()=>s.media({user:b,recordId:legacy.id,fileId:video.id}),/social_not_found/);
  const pending=(await write(a,"thread",{userId:b.sub})).record;
  const pair=await Promise.all([write(a,"friend-request",{userId:b.sub}),write(b,"friend-request",{userId:a.sub})]);
  assert.equal(pair[0].record.id,pair[1].record.id); const friend=pair[0].record;
  assert.equal((await s.friends({user:a})).items.length,1);
  await assert.rejects(()=>write(a,"friend-review",{recordId:friend.id,accept:true}),/social_forbidden/);
  await assert.rejects(()=>write(c,"friend-review",{recordId:friend.id,accept:true}),/social_not_found/);
  assert.equal((await s.notifications.list(b.sub,undefined,"friends")).items.length,1);
  await write(b,"friend-review",{recordId:friend.id,accept:true});
  assert.equal((await repo.get(pending.id)).status,"accepted","accepting friendship also accepts an existing conversation request");
  assert.equal((await s.friends({user:a})).items[0].status,"accepted");
  assert((await s.notifications.list(a.sub,undefined,"friends")).items.some(n=>n.type==="friend-accepted"));
  assert.equal((await s.notifications.list(b.sub,undefined,"friends")).items.length,0);
  await write(b,"profile",{name:"Betty",bio:"Private again",discoverable:false});
  const thread=(await write(a,"thread",{userId:b.sub})).record; assert.equal(thread.status,"accepted");
  await write(b,"friend-remove",{recordId:friend.id}); assert.equal((await s.friends({user:a})).items.length,0);
  await write(b,"profile",{name:"Betty",discoverable:true});
  const newRequest=(await write(b,"friend-request",{userId:a.sub})).record;
  assert.notEqual(newRequest.eventId,friend.eventId); await write(b,"friend-cancel",{recordId:friend.id});
  assert.equal((await s.notifications.list(a.sub,undefined,"friends")).items.length,0);
  const again=(await write(a,"friend-request",{userId:b.sub})).record;
  await write(b,"friend-review",{recordId:again.id,accept:false});
  assert((await s.notifications.list(a.sub,undefined,"friends")).items.some(n=>n.type==="friend-declined"));
  await write(a,"block",{userId:b.sub});
  assert.equal((await s.notifications.list(a.sub,undefined,"friends")).items.length,0);
  await assert.rejects(()=>write(b,"friend-request",{userId:a.sub}),/social_not_found/);
  await write(a,"block",{userId:b.sub,enabled:false});
  const opt={enabled:true,adultConfirmed:true,gender:"female",preferences:["female"],syncProfile:true};
  await write(a,"connect",opt); await write(b,"connect",{...opt,syncProfile:false,name:"Private alias",bio:"Connect bio"});
  await write(c,"connect",{...opt,gender:"male",preferences:["male"]});
  const discover=(await s.read({user:a,module:"connect"})).items;
  assert(discover.some(r=>r.ownerId===b.sub)); assert(!discover.some(r=>r.ownerId===c.sub));
  const alias=discover.find(r=>r.ownerId===b.sub);
  for(const key of ["gender","preferences","syncProfile","consentedAt"]) assert.equal(alias[key],undefined);
  assert.equal(alias.author.name,"Private alias"); assert(!JSON.stringify(alias).includes("Betty"));
  await assert.rejects(()=>s.read({user:c,recordId:"connect:"+a.sub}),/social_not_found/);
  await assert.rejects(()=>s.media({user:c,recordId:"connect:"+a.sub,fileId:image.id}),/social_not_found/);
  assert.equal((await s.read({user:b,recordId:"connect:"+a.sub})).record.files[0].id,image.id);
  await write(a,"profile",{name:"Updated Alice",bio:"Updated private bio",fileIds:[image.id]});
  assert.equal((await repo.get("connect:"+a.sub)).name,"Updated Alice");
  await write(b,"profile",{name:"New Betty",bio:"Never sync",discoverable:true});
  assert.equal((await repo.get("connect:"+b.sub)).name,"Private alias");
  await write(a,"interest",{userId:b.sub});await write(b,"interest",{userId:a.sub});
  const match=(await write(a,"thread",{userId:b.sub,context:"connect"})).record;
  assert(!(await s.read({user:a,module:"talk"})).items.some(r=>r.id===match.id));
  assert((await s.read({user:a,module:"connect",mode:"chats"})).items.some(r=>r.id===match.id));
  assert.equal((await s.read({user:a,recordId:match.id})).record.module,"connect");
  await write(b,"message",{recordId:match.id,text:"Private Connect message"});
  const connectNotice=(await s.notifications.list(a.sub,undefined,"connect")).items.find(n=>n.type==="message");
  assert.equal(connectNotice.name,"Private alias");assert.equal(connectNotice.target.module,"connect");
  await write(b,"call",{recordId:match.id,video:false});assert.equal((await s.inbox({user:a})).calls[0].context,"connect");
  // Filtering happens before pagination even when many newer notices belong to a different menu.
  for(let i=0;i<35;i++) await write(b,"comment",{recordId:post.id,text:"Watch comment "+i});
  for(let i=0;i<36;i++) await write(b,"comment",{recordId:clip.id,text:"Short comment "+i});
  let page=await s.notifications.list(a.sub,undefined,"watch");
  assert.equal(page.items.length,30);assert(page.items.every(n=>n.module==="watch"));assert.equal(page.counts.watch,35);
  const older=await s.notifications.list(a.sub,page.nextCursor,"watch");assert.equal(older.items.length,5);
  assert(!older.items.some(n=>page.items.some(x=>x.id===n.id)));
  const shortCount=page.counts.short;await s.notifications.read(a.sub,page.items.map(n=>n.id));
  page=await s.notifications.list(a.sub,undefined,"short");assert.equal(page.counts.short,shortCount);assert.equal(page.counts.watch,5);
  await assert.rejects(()=>s.notifications.list(a.sub,undefined,"unknown"),/social_invalid_module/);
  const admin={...d,roles:["administrator"],permissions:["chat","settings"]};
  await write(admin,"moderate",{recordId:"profile:"+a.sub,hidden:true,reason:"Fixture"});
  assert.equal((await s.notifications.list(a.sub,undefined,"profile")).items[0].target,null);
  assert.equal((await s.people({user:d,query:"Alice"})).items.length,0);
  await write(a,"profile",{name:"Updated Alice",discoverable:true});
  assert.equal((await repo.get("profile:"+a.sub)).hidden,true,"editing a profile does not undo moderation");
  console.log("Social redesign: image/text Watch, video Short + legacy IDs, private profiles/media, friend lifecycle, private Connect sync and matching, separate chats and scoped notification pagination passed");
}
if(require.main===module) suite(new SocialRepository({allowMemory:true})).catch(error=>{console.error(error);process.exitCode=1;});
module.exports={suite};
