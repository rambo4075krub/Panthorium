"use strict";
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { SocialRepository } = require("../services/socialRepository");
const { SocialService } = require("../services/socialService");
const { noticeId } = require("../services/socialNotifications");
async function suite(repo) {
  await repo.init();
  const service = new SocialService({ repository: repo, files: {} });
  const users = Array.from({ length: 4 }, () => ({ sub: randomUUID(), roles: ["user"], permissions: ["chat"] }));
  const [a, b, c, d] = users;
  const write = (user, action, input, requestId = randomUUID()) => service.write({ user, action, input, requestId });
  const list = (user, before) => service.notifications.list(user.sub, before);
  const find = async (user, type) => (await list(user)).items.find(n => n.type === type);
  for (const [index, user] of users.entries()) await write(user, "profile", { name: "Name " + index, discoverable: true });
  await list(a); await list(b);
  const requestKey = randomUUID();
  const thread = (await write(a, "thread", { userId: b.sub }, requestKey)).record;
  await write(a, "thread", { userId: b.sub }, requestKey);
  await write(b, "thread", { userId: a.sub });
  const invitation = await find(b, "thread-request");
  assert(invitation); assert.equal(invitation.name, "Name 0");
  assert.equal((await list(b)).unreadCount, 1); assert.equal((await list(a)).unreadCount, 0);
  assert.equal(invitation.target.recordId, thread.id);
  assert.equal((await list(c)).unreadCount, 0);
  await assert.rejects(() => service.notifications.read(c.sub, [invitation.id]), /social_not_found/);
  await assert.rejects(() => service.notifications.read(b.sub, [invitation.id, "notification:" + "f".repeat(64)]), /social_not_found/);
  assert.equal((await list(b)).unreadCount, 1, "invalid acknowledgement is atomic");
  await service.notifications.read(b.sub, [invitation.id]);
  assert.equal((await list(b)).unreadCount, 0);
  assert.equal((await repo.get(thread.id)).status, "pending", "reading notice does not accept request");
  await write(b, "accept-thread", { recordId: thread.id, accept: true });
  assert(await find(a, "thread-accepted")); assert(!await find(b, "thread-request"));
  const message = (await write(a, "message", { recordId: thread.id, text: "private content stays in chat" })).record;
  const messageNotice = await find(b, "message");
  assert(!JSON.stringify(messageNotice).includes(message.text));
  await service.notifications.read(b.sub, [messageNotice.id]);
  assert.equal((await repo.get(message.id)).readAt, undefined, "acknowledging alert does not send read receipt");
  const second = (await write(a, "message", { recordId: thread.id, text: "two" })).record;
  await service.markRead({ user: b, recordId: thread.id, messageIds: [second.id] });
  assert((await repo.get(noticeId("message", second.id, b.sub))).readAt);
  assert.equal((await list(b)).unreadCount, 0);
  const third = (await write(a, "message", { recordId: thread.id, text: "deleted" })).record;
  await write(a, "delete", { recordId: third.id });
  assert(!(await list(b)).items.some(n => n.id === noticeId("message", third.id, b.sub)));
  await write(b, "block", { userId: a.sub });
  assert.equal((await list(b)).unreadCount, 0); assert.equal((await list(b)).items.length, 0);
  await write(b, "block", { userId: a.sub, enabled: false });
  const declined = (await write(a, "thread", { userId: c.sub })).record;
  await write(c, "accept-thread", { recordId: declined.id, accept: false });
  assert(await find(a, "thread-declined"));
  // Existing pending requests from before this release are seeded once.
  const legacy = (await write(d, "thread", { userId: b.sub })).record;
  await repo.remove(noticeId("thread-request", legacy.id, b.sub)); await repo.remove("notification-init:" + b.sub);
  assert((await list(b)).items.some(n => n.target.recordId === legacy.id));
  const beforeSeed = (await list(b)).unreadCount; await list(b); assert.equal((await list(b)).unreadCount, beforeSeed);

  const post = (await write(a, "publish", { module: "community", text: "post" })).record;
  const comment = (await write(b, "comment", { recordId: post.id, text: "reply" })).record;
  assert.equal((await find(a, "comment")).target.recordId, post.id);
  await write(b, "like", { recordId: post.id }); assert(await find(a, "like"));
  await write(b, "like", { recordId: post.id }); assert(!await find(a, "like"));
  await write(b, "follow", { userId: a.sub }); assert(await find(a, "follow"));
  await write(b, "follow", { userId: a.sub, enabled: false }); assert(!await find(a, "follow"));
  await write(b, "delete", { recordId: comment.id }); assert(!await find(a, "comment"));
  const listing = (await write(a, "listing", { title: "Test", priceSatang: 100, stock: 2 })).record;
  const order = (await write(b, "order", { recordId: listing.id, quantity: 1 })).record;
  assert((await find(a, "order-requested")).target.orders);
  await write(a, "order-status", { recordId: order.id, status: "accepted" }); assert(await find(b, "order-accepted"));
  await write(a, "order-status", { recordId: order.id, status: "fulfilled" }); assert(await find(b, "order-fulfilled"));

  for (const [user, name] of [[a, "Alias A"], [b, "Alias B"]]) await write(user, "connect", { enabled: true, adultConfirmed: true, name, gender: "male", preferences: ["all"] });
  await write(a, "interest", { userId: b.sub }); assert(!await find(b, "connect-match"));
  await write(b, "interest", { userId: a.sub });
  assert.equal((await find(a, "connect-match")).name, "Alias B");
  assert.equal((await find(b, "connect-match")).name, "Alias A");
  await write(a, "connect", { enabled: false }); assert(!await find(b, "connect-match"));
  const call = (await write(a, "call", { recordId: thread.id, video: true })).record;
  assert(await find(b, "call"));
  await repo.put({ ...call, expiresAt: new Date(Date.now() - 1).toISOString() });
  assert(await find(b, "call-missed"));
  const live = (await write(a, "live-start", { title: "Test live" })).record;
  await write(b, "live-join", { recordId: live.id }); await write(a, "live-end", { recordId: live.id });
  assert(await find(b, "live-ended"));
  await write({ ...d, roles: ["administrator"], permissions: ["chat", "settings"] }, "moderate", { recordId: post.id, hidden: true, reason: "Review" });
  const moderation = await find(a, "moderation-hidden"); assert(moderation); assert.equal(moderation.target, null); assert.equal(moderation.reason, "Review");

  // Pagination and unread totals include more than one page without clearing new arrivals.
  await list(d);
  const td = (await write(c, "thread", { userId: d.sub })).record; await write(d, "accept-thread", { recordId: td.id, accept: true });
  for (let i = 0; i < 35; i++) await write(c, "message", { recordId: td.id, text: String(i) });
  const page = await list(d); assert.equal(page.items.length, 30); assert.equal(page.unreadCount, 35);
  const next = await list(d, page.nextCursor); assert.equal(next.items.length, 5);
  assert.equal(new Set([...page.items, ...next.items].map(n => n.id)).size, 35);
  await assert.rejects(() => list(c, page.nextCursor), /social_not_found/);
  await write(c, "message", { recordId: td.id, text: "arrived during acknowledgement" });
  await service.notifications.read(d.sub, page.items.map(n => n.id)); assert.equal((await list(d)).unreadCount, 6);
  const restarted = new SocialService({ repository: repo, files: {} });
  assert.equal((await restarted.notifications.list(d.sub)).unreadCount, 6);
  console.log("Social notifications: requests, acceptance, messages, calls, commerce, Connect privacy, revocation, deduplication, pagination and durable acknowledgements passed");
}
if (require.main === module) suite(new SocialRepository({ allowMemory: true })).catch(e => { console.error(e); process.exitCode = 1; });
module.exports = { suite };
