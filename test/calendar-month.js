'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
process.env.TZ = 'Asia/Bangkok';
(async () => {
  const dom = new JSDOM('<body></body>', { runScripts:'outside-only', url:'https://panthorium.test' });
  const w = dom.window;
  w.OS = {windows:new Map(),state:{user:{sub:'owner',roles:['user'],permissions:['chat']}},config:{backendUrl:'https://panthorium.test'}};
  w.createWindow = (id,title,markup) => { w.OS.windows.set(id,true); const el=w.document.createElement('div'); el.className='window'; el.dataset.id=id; el.innerHTML=markup; w.document.body.appendChild(el); };
  w.focusWindow = () => {};
  const record = {memoryId:'event',title:'<img src=x onerror=alert(1)> นัดประชุม',content:JSON.stringify({version:1,startsAt:'2028-02-28T18:30:00Z',description:'รายละเอียด'})};
  w.authorizedFetch = async () => ({ok:true,json:async()=>({ok:true,memories:[record]})});
  w.eval(fs.readFileSync('calendar-ui.js','utf8'));
  w.eval(fs.readFileSync('voice-window-catalog.js','utf8'));
  w.eval(fs.readFileSync('voice-command-client.js','utf8'));
  await w.PanthoriumCalendar.open();
  const q=s=>w.document.querySelector(s);
  const date=q('[data-calendar-date]');
  const select=value=>{date.value=value;date.dispatchEvent(new w.Event('change'));};
  assert.equal((await w.PanthoriumVoiceCommands.windowAction('calendar_view:'+encodeURIComponent(JSON.stringify({action:'date',date:'2028-02-01'})))).ok,true);
  assert.equal(date.value,'2028-02-01');
  await w.PanthoriumCalendar.command({action:'new_event',date:'2028-02-02',title:'เสียง'});
  assert.equal(q('[data-calendar-editor]').open,true);assert.equal(q('[data-calendar-title]').value,'เสียง');
  assert.equal((await w.PanthoriumCalendar.command({action:'date',date:'2028-02-31'})).ok,false);
  select('2028-02-01');
  assert.equal(w.document.querySelectorAll('[data-calendar-day]').length,42);
  assert.equal(w.document.querySelectorAll('[data-calendar-day]:not([data-outside])').length,29);
  assert(q('[data-calendar-month]').textContent.includes('กุมภาพันธ์'));
  const leap=q('[data-calendar-day="2028-02-29"]');
  assert.match(leap.textContent,/1 นัด/,'UTC event belongs to Feb 29 in Bangkok');
  leap.click();
  assert.equal(date.value,'2028-02-29');
  assert.match(q('[data-calendar-events]').textContent,/นัดประชุม/);
  assert.equal(w.document.querySelector('img'),null,'titles are literal text');
  q('[data-calendar-next]').click();
  assert.equal(date.value,'2028-03-01');
  q('[data-calendar-prev]').click(); assert.equal(date.value,'2028-02-01');
  select('2027-12-31'); q('[data-calendar-next]').click(); assert.equal(date.value,'2028-01-01');
  q('[data-calendar-day="2028-01-01"]').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}));
  assert.equal(date.value,'2027-12-31');
  select('2027-02-01'); assert.equal(w.document.querySelectorAll('[data-calendar-day]:not([data-outside])').length,28);
  q('[data-calendar-today]').click(); assert(q('[aria-current="date"][aria-pressed="true"]'));
  record.content=JSON.stringify({version:1,startsAt:'2028-02-29T09:00:00+07:00',endsAt:'2028-02-29T10:00:00+07:00',additionalStartsAt:['2028-03-07T09:00:00+07:00','2028-03-14T09:00:00+07:00'],excludedStartsAt:['2028-03-14T09:00:00+07:00'],occurrenceOverrides:{'2028-03-07T09:00:00+07:00':{startsAt:'2028-03-08T11:00:00+07:00',endsAt:'2028-03-08T12:00:00+07:00',title:'เลื่อนประชุม',location:'ห้องหนึ่ง'}}});
  await w.PanthoriumCalendar.refresh();select('2028-03-08');
  assert.match(q('[data-calendar-events]').textContent,/เลื่อนประชุม/);
  assert.match(q('[data-calendar-events]').textContent,/ห้องหนึ่ง/);
  assert.doesNotMatch(q('[data-calendar-day="2028-03-07"]').textContent,/นัด/);
  assert.doesNotMatch(q('[data-calendar-day="2028-03-14"]').textContent,/นัด/);
  let late;
  w.authorizedFetch=()=>new Promise(resolve=>{late=resolve;});
  q('[data-calendar-refresh]').click();
  w.OS.state.user={sub:'guest:changed',roles:['guest']};
  w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  assert.equal((await w.PanthoriumVoiceCommands.windowAction('calendar_view:'+encodeURIComponent(JSON.stringify({action:'today'})))).ok,false);
  late({ok:true,json:async()=>({ok:true,memories:[record]})});
  await new Promise(resolve=>setTimeout(resolve,10));
  select('2028-02-29'); assert.doesNotMatch(q('[data-calendar-events]').textContent,/นัดประชุม/);
  dom.window.close();
  console.log('Calendar month: 42 cells, leap years, year rollover, local-time event placement, selection, keyboard, safe titles and account isolation passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
