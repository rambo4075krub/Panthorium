"use strict";
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { SocialRepository } = require("../services/socialRepository");
const { SocialService } = require("../services/socialService");
const { TALK_MESSAGE_TTL, expired, expiresAt } = require("../services/socialRetention");
async function suite(repo) {
  const [a, b, c] = Array.from({ length: 3 }, () => ({ sub: randomUUID(), roles: ["user"], permissions: ["chat"] }));
  const file = { id: randomUUID(), name: "private.png", contentType: "image/png", size: 4 };
  const s = new SocialService({ repository: repo, files: { findObject: async () => file, preview: async () => ({ body: Buffer.from("test") }) },
    accounts: { findUserById: async id => ({ id, username: "Registered friend", roles: ["administrator"], permissions: ["chat"] }) } });
  await s.init();
  const write = (user, action, input = {}) => s.write({ user, action, input, requestId: randomUUID() });
  await write(a, "profile", { name: "Alice", discoverable: true });
  await write(b, "profile", { name: "Betty", discoverable: true });
  await write(c, "profile", { name: "Carl", discoverable: true });
  const thread = (await write(a, "thread", { userId: b.sub })).record;
  await write(b, "accept-thread", { recordId: thread.id, accept: true });
  const requestId = randomUUID(), input = { recordId: thread.id, text: "Secret retained for three days", fileIds: [file.id] };
  const sent = (await s.write({ user: a, action: "message", input, requestId })).record;
  assert.equal(Date.parse(sent.expiresAt) - Date.parse(sent.createdAt), TALK_MESSAGE_TTL);
  let list = await s.read({ user: a, module: "talk" });
  assert.equal(list.items[0].peer.name, "Betty");
  assert.equal((await s.read({ user: b, module: "talk" })).items[0].peer.name, "Alice");
  assert.equal(list.items[0].lastMessage.text, input.text);
  assert.equal(list.items[0].lastMessage.attachmentCount, 1);
  assert.equal(list.items[0]._latestMessage, undefined);
  assert.equal((await s.read({ user: a, module: "talk", query: "Betty" })).items.length, 1);
  const boundary = Date.parse(sent.createdAt) + TALK_MESSAGE_TTL;
  assert.equal(expired(sent, thread, boundary - 1), false);
  assert.equal(expired(sent, thread, boundary), true);
  const old = { ...sent, createdAt: new Date(Date.now() - TALK_MESSAGE_TTL - 1000).toISOString() };
  old.expiresAt = expiresAt(old); await repo.put(old);
  const receipts = await repo.list({ kind: "receipt", owner: a.sub, limit: 200 });
  const receipt = receipts.find(r => r.result?.record?.id === sent.id);
  await repo.put({ ...receipt, result: { ok: true, record: old } });
  // Exact access cutoff works even when physical cleanup is throttled.
  s.retentionAt = Date.now();
  assert.equal(await s.allowed(repo, b.sub, old), false);
  await assert.rejects(() => s.media({ user: b, recordId: old.id, fileId: file.id }), /social_not_found/);
  await assert.rejects(() => s.markRead({ user: b, recordId: thread.id, messageIds: [old.id] }), /social_not_found/);
  assert.equal((await s.read({ user: b, recordId: thread.id })).items.length, 0);
  assert.equal((await s.read({ user: b, module: "talk" })).items[0].lastMessage, null);
  assert(!(await s.notifications.list(b.sub)).items.some(n => n.target?.recordId === old.id || n.type === "message"));
  assert.equal((await s.write({ user: a, action: "message", input, requestId })).expired, true);
  assert(!JSON.stringify(await repo.get(receipt.id)).includes(input.text));
  // Legacy copies, including already manually deleted messages, must also be scrubbed.
  await repo.put({ ...receipt, result: { ok: true, record: old } });
  const connect = { ...thread, id: "connect-test:" + randomUUID(), context: "connect" };
  const support = { ...thread, id: "support-test:" + randomUUID(), context: "support", supportAdminId: b.sub };
  const group = (await write(a, "group-create", { title: "My group", privacy: "closed" })).record;
  await repo.put(connect); await repo.put(support);
  const kept = { ...old, id: "keep:" + randomUUID(), parentId: connect.id };
  const keptGroup = { ...old, id: "group-message:" + randomUUID(), kind: "group-message", parentId: group.id };
  const supportMessage = { ...old, id: "support-message:" + randomUUID(), parentId: support.id };
  await repo.put(kept); await repo.put(keptGroup); await repo.put(supportMessage);
  const results = await Promise.all([s.purgeExpiredMessages(), new SocialService({ repository: repo }).purgeExpiredMessages()]);
  assert(results.some(r => r.deletedMessages >= 2));
  assert.equal(await repo.get(old.id), null); assert.equal(await repo.get(supportMessage.id), null);
  assert(await repo.get(kept.id)); assert(await repo.get(keptGroup.id));
  assert(!JSON.stringify(await repo.get(receipt.id)).includes(input.text));
  assert.equal((await s.write({ user: a, action: "message", input, requestId })).expired, true, "replay cannot resend expired content");
  assert.equal(await repo.get(old.id), null);
  const notices = await repo.list({ kind: "notification", owner: b.sub, limit: 200 });
  assert(!notices.some(n => n.targetId === old.id));
  const reply = (await write(b, "message", { recordId: thread.id, text: "Latest reply" })).record;
  assert.equal((await s.read({ user: a, module: "talk" })).items[0].lastMessage.id, reply.id);
  await write(b, "delete", { recordId: reply.id });
  assert.equal((await s.read({ user: a, module: "talk" })).items.find(t => t.id === thread.id).lastMessage, null);
  // Membership is filtered before pagination, including pending requests and groups owned by the caller.
  const joined = (await write(b, "group-create", { title: "Joined", privacy: "open" })).record;
  await write(a, "group-join", { recordId: joined.id });
  const pending = (await write(b, "group-create", { title: "Pending", privacy: "closed" })).record;
  await write(a, "group-join", { recordId: pending.id });
  for (let i = 0; i < 105; i++) await repo.put({ ...pending, id: "zz-group:" + randomUUID() });
  const mine = await s.collections({ user: a, kind: "group", scope: "mine" });
  assert.deepEqual(new Set(mine.items.map(g => g.id)), new Set([group.id, joined.id]));
  const all = await s.collections({ user: a, kind: "group", scope: "all" });
  assert.equal(all.items.length, 100); assert(all.nextCursor);
  const more = await s.collections({ user: a, kind: "group", scope: "all", before: all.nextCursor });
  assert(more.items.some(g => g.id === pending.id));
  // Activity order and stable cursors do not rely on hashed thread ids.
  const seed = { ...thread, ownerId: c.sub, members: [a.sub, c.sub], createdAt: "2025-01-01T00:00:00.000Z" };
  for (let i = 0; i < 102; i++) await repo.put({ ...seed, id: "thread-page:" + randomUUID() });
  const message = (await write(b, "message", { recordId: thread.id, text: "Recent first" })).record;
  list = await s.read({ user: a, module: "talk" });
  assert.equal(list.items[0].id, thread.id); assert.equal(list.items[0].lastMessage.id, message.id);
  const next = await s.read({ user: a, module: "talk", before: list.nextCursor });
  assert.equal(new Set([...list.items, ...next.items].map(t => t.id)).size, 104);
  await assert.rejects(() => s.read({ user: a, module: "talk", before: "invalid" }), /social_invalid_cursor/);
  await write(b, "block", { userId: a.sub });
  assert(!(await s.read({ user: a, module: "talk" })).items.some(t => t.id === thread.id));
  assert.equal((await s.read({ user: c, module: "talk" })).items.some(t => t.id === thread.id), false);
  console.log("Social navigation: peer names/previews, activity pagination, joined groups, exact 72-hour cutoff, media/read/notification denial, physical cleanup and idempotency-copy erasure passed");
}
if (require.main === module) suite(new SocialRepository({ allowMemory: true })).catch(e => { console.error(e); process.exitCode = 1; });
module.exports = { suite };
