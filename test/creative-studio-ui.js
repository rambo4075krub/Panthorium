'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const catalog = require('../voice-window-catalog');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const plugins = ['image', 'video', 'document', 'spreadsheet', 'presentation'];

async function main() {
  const dom = new JSDOM('<!doctype html><html><head></head><body><div id="start-menu"><div id="sm-apps"></div></div></body></html>', { url: 'https://panthorium.test/', runScripts: 'outside-only' });
  const w = dom.window, calls = [], store = new Map(), created = [], revoked = [];
  let login = 0, files = [{ id: 'source-a', name: '<img src=x onerror=alert(1)>.png', contentType: 'image/png', size: 120 }], jobs = [], failSubmission = false, pendingSubmission = null, fileFetch = null;
  const owner = { sub: 'owner', roles: ['user'], permissions: ['chat'] };
  w.OS = { state: { user: owner }, config: { backendUrl: 'https://backend.test', accessToken: 'account-token' }, windows: store };
  w.PanthoriumAccounts = { openLogin: () => login++ };
  w.PanthoriumWindowCatalog = catalog;
  w.createWindow = (id, title, html, options) => { const el = w.document.createElement('section'); el.className = 'window'; el.dataset.id = id; el.innerHTML = html; w.document.body.append(el); store.set(id, { el, onClose: options.onClose }); };
  w.closeWindow = id => { const rec = store.get(id); rec?.onClose?.(); rec?.el.remove(); store.delete(id); };
  w.PanthoriumWindowManager = { restore: id => { const rec = store.get(id); if (rec) rec.el.style.display = 'flex'; } };
  w.URL.createObjectURL = blob => { created.push(blob); return 'blob:test-' + created.length; };
  w.URL.revokeObjectURL = url => revoked.push(url);
  w.HTMLAnchorElement.prototype.click = function () { this.dataset.clicked = 'true'; };
  const response = (data, status = 200) => ({ ok: status < 400, status, json: async () => data, blob: async () => new w.Blob(['private content']) });
  w.fetch = async (url, options = {}) => {
    calls.push({ url, options });
    if (url.endsWith('/api/studio/catalog')) return response({ ok: true, durable: true, plugins: plugins.map(id => ({ id, title: id, available: true, mode: 'auto' })) });
    if (url.endsWith('/api/studio/jobs') && options.method !== 'POST') return response({ ok: true, jobs });
    if (url.endsWith('/api/files')) return response({ ok: true, files });
    if (url.includes('/api/files/')) return fileFetch ? fileFetch : response({ ok: true });
    if (url.includes('/mode')) return response({ ok: true });
    if (url.endsWith('/api/studio/jobs') && options.method === 'POST') {
      if (failSubmission) throw Error('network failed');
      if (pendingSubmission) return pendingSubmission;
      const body = JSON.parse(options.body), job = { id: 'job-' + (jobs.length + 1), status: 'completed', createdAt: new Date().toISOString(), steps: body.steps || [{ ...body, status: 'completed' }], files: [{ id: 'output-a', name: '<svg onload=alert(1)>.png', contentType: 'image/png', size: 48 }] };
      jobs.unshift(job); return response({ ok: true, job });
    }
    if (url.endsWith('/advance')) return response({ ok: true, job: { id: 'background', status: 'completed', steps: [{ pluginId: 'document', status: 'completed' }], files: [] } });
    if (url.endsWith('/confirm')) return response({ ok: true, output: { job: { id: 'from-sentinel', status: 'completed', steps: [{ pluginId: 'image', status: 'completed' }], files: [] } } });
    if (url.endsWith('/cancel')) return response({ ok: true });
    throw Error('Unexpected URL ' + url);
  };
  w.eval(fs.readFileSync(require.resolve('../start-menu-ui.js'), 'utf8'));
  w.eval(fs.readFileSync(require.resolve('../creative-studio-ui.js'), 'utf8'));
  w.document.dispatchEvent(new w.Event('DOMContentLoaded')); await tick();
  const group = w.document.querySelector('[data-start-group="creative"]');
  assert(group);
  assert.equal(group.querySelectorAll('.sm-app').length, 5);
  assert.equal(group.querySelector('.sm-group-label').textContent, 'สร้างสรรค์และเอกสาร');
  assert.equal(group.querySelector('[data-start-group-items]').hidden, true);
  for (const id of plugins) assert(catalog.allowed(catalog.apps.find(item => item.id === 'studio-' + id), owner));
  assert.equal(catalog.parse('เปิดสตูดิโอรูปภาพ').action, 'open_studio_image');
  assert.equal(catalog.parse('เปิดสตูดิโอเอกสาร').action, 'open_studio_document');

  let root = w.PanthoriumCreativeStudio.open('image'); await tick(); await tick();
  assert(root);
  assert.equal(root.querySelectorAll('[role=tab]').length, 5);
  assert.equal(root.querySelector('[data-studio-submit]').disabled, false);
  assert.equal(root.querySelector('[data-studio-files] img'), null, 'untrusted filename is text');
  assert.match(root.querySelector('[data-studio-files]').textContent, /<img src=x/);
  assert(root.querySelector('[data-studio-durability]').textContent.includes('คลาวด์'));
  root.querySelector('[data-studio-prompt]').value = 'สร้างภาพตัวอย่าง';
  root.querySelector('[data-studio-form]').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick();
  assert.equal(calls.filter(c => c.options.method === 'POST').length, 0, 'media generation requires explicit confirmation');
  root.querySelector('[data-studio-confirm]').checked = true;
  failSubmission = true;
  root.querySelector('[data-studio-form]').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick();
  assert.equal(root.querySelector('[data-studio-prompt]').value, 'สร้างภาพตัวอย่าง');
  const failedBody = JSON.parse(calls.find(c => c.url.endsWith('/api/studio/jobs') && c.options.method === 'POST').options.body);
  assert.match(root.querySelector('[data-studio-status]').textContent, /เชื่อมต่อไม่สำเร็จ/);
  failSubmission = false;
  let resolveSubmission;
  pendingSubmission = new Promise(resolve => { resolveSubmission = resolve; });
  root.querySelector('[data-studio-form]').dispatchEvent(new w.Event('submit', { cancelable: true }));
  root.querySelector('[data-studio-form]').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick();
  const submissions = calls.filter(c => c.url.endsWith('/api/studio/jobs') && c.options.method === 'POST');
  assert.equal(submissions.length, 2, 'double clicks cannot create concurrent submissions');
  assert.equal(JSON.parse(submissions[1].options.body).idempotencyKey, failedBody.idempotencyKey, 'retry after uncertain result keeps idempotency key');
  assert.equal(root.querySelector('[data-studio-submit]').disabled, true);
  resolveSubmission(response({ ok: true, job: { id: 'safe-job', status: 'completed', summary: '<script>alert(1)</script>', steps: [{ pluginId: 'image', status: 'completed' }], files: [{ id: 'output-a', name: '<svg onload=alert(1)>.png', contentType: 'image/png' }, { id: 'print-only', name: 'report.print.html', contentType: 'text/html' }, { id: 'webp-only', name: 'image.webp', contentType: 'image/webp' }, { id: 'native-docx', name: 'report.docx', contentType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }] } }));
  pendingSubmission = null; await tick(); await tick();
  assert.equal(root.querySelector('[data-studio-jobs] script'), null);
  assert.equal(root.querySelector('[data-studio-jobs] svg'), null);
  assert.match(root.querySelector('[data-studio-jobs]').textContent, /<script>alert/);
  for (const id of ['print-only', 'webp-only']) assert.equal(root.querySelector('[data-download-file="' + id + '"]').closest('.cs-result').querySelector('[data-send-to]'), null, 'unsupported sources do not offer a misleading handoff');
  assert(root.querySelector('[data-download-file="native-docx"]').closest('.cs-result').querySelector('[data-send-to="presentation"]'), 'native office files can be reused');
  root.querySelector('[data-download-file]').click(); await tick();
  const download = calls.find(c => c.url.endsWith('/api/files/output-a'));
  assert.equal(download.options.headers.Authorization, 'Bearer account-token');
  assert.equal(download.options.credentials, 'include'); assert.equal(created.length, 1);
  root.querySelector('[data-send-to="presentation"]').click();
  assert.equal(root.dataset.studioActive, 'presentation');
  assert(root.querySelector('[data-source-file-id="output-a"]').checked, 'handoff carries actual owned file ID');
  const mode = root.querySelector('[data-studio-mode]'); mode.value = 'never'; mode.dispatchEvent(new w.Event('change')); await tick();
  assert.equal(root.querySelector('[data-studio-submit]').disabled, true);
  assert.equal(JSON.parse(calls.find(c => c.url.endsWith('/plugins/presentation/mode')).options.body).mode, 'never');
  mode.value = 'auto'; mode.dispatchEvent(new w.Event('change')); await tick();
  assert.equal(root.querySelector('[data-studio-submit]').disabled, false);

  w.PanthoriumCreativeStudio.openSpreadsheet();
  root.querySelector('[data-studio-prompt]').value = 'สรุปค่าใช้จ่าย';
  const next = root.querySelector('[data-studio-next]'); next.value = 'document'; next.dispatchEvent(new w.Event('change'));
  root.querySelector('[data-studio-next-prompt]').value = 'จัดรายงานพร้อมสรุปยอด';
  root.querySelector('[data-studio-form]').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick();
  const workflow = JSON.parse(calls.filter(c => c.url.endsWith('/api/studio/jobs') && c.options.method === 'POST').at(-1).options.body);
  assert.equal(workflow.steps[0].pluginId, 'spreadsheet');
  assert.equal(workflow.steps[1].pluginId, 'document'); assert.equal(workflow.steps[1].usePrevious, true);
  assert.equal(workflow.steps[1].input.prompt, 'จัดรายงานพร้อมสรุปยอด');
  assert.notEqual(workflow.idempotencyKey, failedBody.idempotencyKey);

  const approval = { toolId: 'studio.create', ok: false, requiresConfirmation: true, actionId: 'approval-a', confirmation: { toolId: 'studio.create', actionId: 'approval-a', approvalHash: 'a'.repeat(64), approvalExpiresAt: new Date(Date.now() + 300000).toISOString(), args: { pluginId: 'image', input: { prompt: '<img src=x> approved image' }, sourceFileIds: ['source-a'] } } };
  w.dispatchEvent(new w.CustomEvent('panthorium:ai-done', { detail: { toolResults: [approval] } })); await tick();
  assert(root.querySelector('[data-studio-approval]'));
  assert.equal(root.querySelector('[data-studio-approval] img'), null);
  assert.match(root.querySelector('[data-studio-approval]').textContent, /source-a/);
  root.querySelector('[data-studio-approve]').click(); root.querySelector('[data-studio-approve]').click(); await tick();
  const confirmations = calls.filter(c => c.url.endsWith('/api/actions/approval-a/confirm'));
  assert.equal(confirmations.length, 1);
  assert.deepEqual(JSON.parse(confirmations[0].options.body), { approvalHash: 'a'.repeat(64) }, 'approval cannot replace the server-bound tool arguments');
  assert(root.querySelector('[data-job-id="from-sentinel"]'));

  const beforeAuthRefresh = root;
  w.OS.config.accessToken = 'new-token'; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  assert.equal(w.document.querySelector('[data-studio]'), beforeAuthRefresh, 'same-account token refresh preserves window');
  w.document.getElementById('sm-apps').replaceChildren(); await tick();
  assert.equal(w.document.querySelectorAll('[data-start-group="creative"] .sm-app').length, 5, 'menu survives shell rebuild');
  w.OS.state.user = { sub: 'guest:1', roles: ['guest'], permissions: ['chat'] }; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  assert.equal(w.document.querySelector('[data-studio]'), null, 'logout clears file names, history, approval details and drafts');
  assert.equal(w.document.querySelector('[data-start-group="creative"]'), null);
  assert(calls.every(c => c.options.signal.aborted), 'logout aborts all account-bound requests');
  assert.deepEqual(revoked, ['blob:test-1']);
  assert.equal(w.PanthoriumCreativeStudio.open(), false); assert.equal(login, 1);

  w.OS.state.user = owner; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  jobs = [{ id: 'late-private', status: 'completed', files: [{ id: 'late-file', name: 'private-file.pdf' }] }];
  root = w.PanthoriumCreativeStudio.openDocument(); await tick(); await tick();
  let resolveFile; fileFetch = new Promise(resolve => { resolveFile = resolve; });
  root.querySelector('[data-download-file]').click(); await tick();
  w.OS.state.user = { sub: 'other-account', roles: ['user'], permissions: ['chat'] }; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  resolveFile(response({ ok: true })); await tick();
  assert.equal(created.length, 1, 'late private response cannot become a blob after account switch');
  assert.equal(w.document.querySelector('[data-studio]'), null);
  assert(catalog.apps.filter(item => item.id === 'creative-studio' || item.id.startsWith('studio-')).every(item => !catalog.allowed(item, { sub: 'guest:x', roles: ['guest'], permissions: ['chat'] })));
  dom.window.close();
  console.log('PASS Creative Studio UI: 5 grouped tools, account-scoped files, paid confirmation, safe text, workflow handoff, idempotent retries, modes, Sentinel approval and logout/late-response cleanup');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
