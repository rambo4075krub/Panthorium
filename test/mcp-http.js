'use strict';
const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
const express = require('express');
const cookieParser = require('cookie-parser');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StreamableHTTPClientTransport } = require('@modelcontextprotocol/sdk/client/streamableHttp.js');
const { AuthService } = require('../services/authService');
const { McpOAuthService } = require('../services/mcpOAuthService');
const { McpOAuthRepository } = require('../services/mcpOAuthRepository');
const { McpToolService } = require('../services/mcpToolService');
const { createMcpRouter } = require('../routes/mcp');

(async () => {
  const origin = 'https://panthorium.example';
  const id = randomUUID();
  const account = { id, username: 'owner-test', roles: [], permissions: ['chat'] };
  const config = { jwtSecret: 'test-mcp-http-secret-not-for-production', accessTokenTtl: '1h' };
  const audit = { record() {} };
  const authService = new AuthService({ config, audit, repository: { async findUserById(userId) { return userId === id ? account : null; } } });
  const user = { ...account, sub: id };
  const uiToken = authService.signAccessToken(account);
  const repository = new McpOAuthRepository({ required: false, allowMemory: true });
  await repository.init();
  const oauth = new McpOAuthService({ repository, authService, baseUrl: origin });
  const toolService = new McpToolService({ baseUrl: origin, agentService: { catalogFor() { return []; }, async execute() { throw new Error('unexpected execution'); } } });
  const app = express();
  app.use(express.json(), cookieParser());
  app.use(createMcpRouter({ oauth, toolService, authService, config, audit }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, body, headers = {}, method = 'POST') => fetch(base + path, { method, headers: { 'content-type': 'application/json', ...headers }, ...(body == null ? {} : { body: JSON.stringify(body) }) });
  let client;
  try {
    const metadata = await (await fetch(base + '/.well-known/oauth-authorization-server')).json();
    assert.deepEqual(metadata.code_challenge_methods_supported, ['S256']);
    assert.equal(metadata.authorization_response_iss_parameter_supported, true);
    assert.equal((await (await fetch(base + '/.well-known/oauth-protected-resource/mcp')).json()).resource, origin + '/mcp');
    const denied = await request('/mcp', { jsonrpc: '2.0', id: 1, method: 'tools/list' });
    assert.equal(denied.status, 401);
    assert.match(denied.headers.get('www-authenticate'), /oauth-protected-resource\/mcp/);
    assert.equal((await request('/mcp', {}, { authorization: `Bearer ${uiToken}` })).status, 401, 'UI JWT cannot enter MCP');
    assert.equal((await request('/oauth/register', { redirect_uris: ['https://attacker.example/callback'] })).status, 400);
    const registration = await (await request('/oauth/register', { client_name: 'ChatGPT', redirect_uris: ['https://chatgpt.com/connector_platform_oauth_redirect'], token_endpoint_auth_method: 'none' })).json();
    assert.ok(registration.client_id);
    const verifier = 'c'.repeat(48);
    const query = new URLSearchParams({ client_id: registration.client_id, redirect_uri: registration.redirect_uris[0], response_type: 'code', code_challenge_method: 'S256', code_challenge: createHash('sha256').update(verifier).digest('base64url'), resource: origin + '/mcp', scope: 'panthorium:read panthorium:media', state: 'state-original' });
    const authorization = await fetch(base + '/oauth/authorize?' + query);
    assert.equal(authorization.status, 200);
    assert.equal(authorization.headers.get('cache-control'), 'no-store');
    assert.match(authorization.headers.get('content-security-policy'), /frame-ancestors 'none'/);
    const cookie = authorization.headers.get('set-cookie').split(';')[0];
    assert.match(authorization.headers.get('set-cookie'), /HttpOnly/);
    const uiHeaders = { authorization: `Bearer ${uiToken}`, cookie, origin };
    const flow = await (await request('/oauth/request', null, uiHeaders, 'GET')).json();
    assert.equal(flow.user.id, id);
    assert.equal((await request('/oauth/authorize', { ...flow, approve: true, csrfToken: 'bad' }, uiHeaders)).status, 400);
    assert.equal((await request('/oauth/authorize', { requestId: flow.requestId, csrfToken: flow.csrfToken, approve: true }, { ...uiHeaders, origin: 'https://attacker.example' })).status, 403);
    const consent = await (await request('/oauth/authorize', { requestId: flow.requestId, csrfToken: flow.csrfToken, approve: true }, uiHeaders)).json();
    const callback = new URL(consent.redirectUrl);
    assert.equal(callback.origin, 'https://chatgpt.com');
    assert.equal(callback.searchParams.get('state'), 'state-original');
    assert.equal(callback.searchParams.get('iss'), origin);
    const tokenBody = new URLSearchParams({ grant_type: 'authorization_code', client_id: registration.client_id, code: callback.searchParams.get('code'), code_verifier: verifier, redirect_uri: registration.redirect_uris[0], resource: origin + '/mcp' });
    const tokenResponse = await fetch(base + '/oauth/token', { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: tokenBody });
    assert.equal(tokenResponse.status, 200);
    const tokens = await tokenResponse.json();
    client = new Client({ name: 'panthorium-http-test', version: '1.0.0' });
    await client.connect(new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { authorization: `Bearer ${tokens.access_token}` } } }));
    const catalog = await client.listTools();
    assert.ok(catalog.tools.some(tool => tool.name === 'panthorium_profile'));
    const profile = await client.callTool({ name: 'panthorium_profile', arguments: {} });
    assert.equal(profile.structuredContent.userId, id);
    const injection = await client.callTool({ name: 'panthorium_profile', arguments: { userId: randomUUID() } });
    assert.equal(injection.isError, true);
    const grants = await (await request('/oauth/grants', null, uiHeaders, 'GET')).json();
    assert.equal(grants.grants.length, 1);
    assert.equal((await request('/oauth/grants/' + grants.grants[0].grantId, null, uiHeaders, 'DELETE')).status, 200);
    assert.equal((await request('/mcp', {}, { authorization: `Bearer ${tokens.access_token}` })).status, 401, 'revocation immediately denies MCP');
    assert.equal((await request('/oauth/authorize', { requestId: flow.requestId, csrfToken: flow.csrfToken, approve: true }, uiHeaders)).status, 400, 'consent cannot replay');
    console.log('mcp-http: discovery, OAuth + PKCE, CSRF, SDK init/list/call, token separation and revocation passed');
  } finally {
    if (client) await client.close();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
