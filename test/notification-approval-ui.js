'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const tick = () => new Promise(resolve => setImmediate(resolve));
async function main() {
  const dom = new JSDOM('<div id="chat-messages"></div>', { url: 'https://panthorium.test', runScripts: 'outside-only' });
  const w = dom.window;
  w.OS = { config: { backendUrl: '' }, state: { user: { id: 'owner', roles: ['user'], permissions: ['chat'] } } };
  w.callAI = async () => ({});
  const calls = [], responses = []; let refreshed = 0;
  w.authorizedFetch = async (url, options) => { calls.push({ url, method: options.method, body: options.body && JSON.parse(options.body) }); const result = responses.shift(); if (result instanceof Error) throw result; return { ok: true, json: async () => result }; };
  w.PanthoriumNotifications = { refresh: () => refreshed++ };
  w.eval(fs.readFileSync(path.join(__dirname, '..', 'notification-event-catalog.js'), 'utf8'));
  w.eval(fs.readFileSync(path.join(__dirname, '..', 'ai-stream-client.js'), 'utf8'));
  let counter = 1;
  const proposal = (args, overrides = {}) => ({ toolId: 'notifications.write', ok: false, requiresConfirmation: true, confirmation: { toolId: 'notifications.write', actionId: '123e4567-e89b-42d3-a456-' + String(counter++).padStart(12, '0'), approvalHash: 'a'.repeat(64), approvalExpiresAt: new Date(Date.now() + 60000).toISOString(), args, ...overrides } });
  const show = (result, accountId = 'owner') => w.dispatchEvent(new w.CustomEvent('panthorium:ai-done', { detail: { accountId, toolResults: [result] } }));
  const request = proposal({ action: 'settings', patch: { events: { operation_succeeded: false }, channels: { voice: true }, quietHours: { start: '22:00', end: '07:00', timeZone: 'Asia/Bangkok' } } });
  show(request); show(request);
  assert.equal(w.document.querySelectorAll('[data-notification-approval]').length, 1, 'same receipt creates one card');
  let card = w.document.querySelector('[data-notification-approval]');
  assert.match(card.textContent, /อ่านการแจ้งเตือนด้วยเสียง: เปิด/); assert.match(card.textContent, /เริ่มเงียบ: 22:00/);
  const eventLabel = w.PanthoriumNotificationCatalog.entries.find(entry => entry.id === 'operation_succeeded').label;
  assert(card.textContent.includes(eventLabel + ': ปิด'), 'the exact event is shown in Thai before approval');
  assert(!card.textContent.includes('operation_succeeded'), 'implementation ids are not the primary approval label');
  assert(!card.textContent.includes('approvalHash')); assert(!card.textContent.includes('"channels"'));
  responses.push({ ok: true, output: { ok: true, settings: {} } });
  card.querySelector('button').click(); await tick(); await tick();
  assert.deepEqual(calls[0], { url: '/api/actions/' + request.confirmation.actionId + '/confirm', method: 'POST', body: { approvalHash: 'a'.repeat(64) } });
  assert.match(card.textContent, /บันทึกตั้งค่าการแจ้งเตือนแล้ว/); assert.equal(refreshed, 1);
  show(request); assert.equal(w.document.querySelectorAll('[data-notification-approval]').length, 1);
  const attack = proposal({ action: 'send', title: '<img src=x onerror=alert(1)>', body: '<script>bad()</script>' }); show(attack);
  card = w.document.querySelector('[data-notification-approval="' + attack.confirmation.actionId + '"]');
  assert(!card.querySelector('img,script')); assert(card.textContent.includes('<script>bad()</script>'));
  const expired = proposal({ action: 'send', title: 'expired' }, { approvalExpiresAt: new Date(Date.now() - 1).toISOString() }); show(expired);
  assert(w.document.querySelector('[data-notification-approval="' + expired.confirmation.actionId + '"] button').disabled);
  show(proposal({ action: 'send', title: 'foreign' }), 'other');
  assert(!w.document.body.textContent.includes('หัวข้อ: foreign'));
  responses.push(new Error('lost response')); card.querySelector('button').click(); await tick(); await tick();
  assert.match(card.textContent, /ยังยืนยันผลไม่ได้/); assert(card.querySelector('button').disabled, 'unknown send is not replayed');
  responses.push({ ok: true, action: { state: 'succeeded', result: { ok: true, output: { ok: true } } } });
  [...card.querySelectorAll('button')].find(button => button.textContent === 'ตรวจผลการดำเนินการ').click(); await tick(); await tick();
  assert.equal(calls.at(-1).method, 'GET'); assert.equal(calls.at(-1).body, undefined); assert.match(card.textContent, /บันทึกการแจ้งเตือนแล้ว/);
  w.OS.state.user = { id: 'other', roles: ['user'], permissions: ['chat'] }; w.dispatchEvent(new w.Event('panthorium:auth-changed'));
  assert.equal(w.document.querySelectorAll('[data-notification-approval]').length, 0);
  show(proposal({ action: 'send', title: 'stale owner response' }), 'owner');
  assert.equal(w.document.querySelectorAll('[data-notification-approval]').length, 0, 'late old-account response cannot expose approval');
  dom.window.close();
  console.log('Notification chat approvals: readable exact scope, immutable credentials, XSS, expiry, replay prevention, outcome reconciliation and account changes passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
